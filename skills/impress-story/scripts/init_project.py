#!/usr/bin/env python3
"""Start a local, editable hand-drawn presentation without network or user media."""
from pathlib import Path
import argparse,json,shutil,subprocess,sys,time
SKILL=Path(__file__).resolve().parents[1]

def initialize(root):
    root=Path(root).resolve()
    if root.exists() and any(root.iterdir()):
        raise ValueError('Project must be absent or empty; existing work will not be overwritten')
    start=time.perf_counter();root.mkdir(parents=True,exist_ok=True)
    (root/'AGENTS.md').write_text('''# Presentation workspace
- content/script.md preserves user input; scenes.json holds stable IDs, notes, positions and freeform SVG art. speech.md and index.html are generated by build.py.
- assets/ holds original media, complete local fonts and licenses; vendor/ holds the pinned impress.js runtime and license. review/ holds only useful verification records.
- Keep editable copy in scene data, not hardcoded in drawing functions. Freeform art may use SVG text, images and paths; update visible art labels when editing their text.
- Establish the audience, desired change and one core message in content/story.md. Do not invent experience or evidence. Keep uncertainty in evidence.md; show decision-relevant conditions where needed.
- Reuse the player, not the scene layout. Hand drawing uses deliberate strokes, readable text and coherent connectors. Do not randomize coordinates or shrink text to hide collisions.
- Text changes use edit_scene.py once; the active preview builds and refreshes. Geometry/motion changes receive targeted real-browser checks. No whole-deck regression for unrelated edits.
- Preserve source media and full fonts. Remove superseded preview screenshots and caches at batch completion. Export/deploy only when authorized; never push Git automatically.
''')
    for d in ['content','assets','vendor','review']:(root/d).mkdir()
    for f in (SKILL/'assets/starter').iterdir():
        if f.is_file():shutil.copy2(f,root/f.name)
    for f in (SKILL/'assets/runtime').iterdir():
        if f.is_file():shutil.copy2(f,root/'vendor'/f.name)
    for f in (SKILL/'assets/fonts').iterdir():
        if f.is_file():shutil.copy2(f,root/'assets'/f.name)
    for name in ['preview.py','edit_scene.py','font_coverage.py']:
        shutil.copy2(SKILL/'scripts'/name,root/name)
    scenes=[
        dict(id='overview',kind='overview',title='先看全局',showTitle=False,notes='此为可替换的启动示意，不代表用户的正式内容。',x=0,y=0,scale=3.2,subtitle='',asset=None,art=''),
        dict(id='question',title='从一个问题开始',notes='启动示意：用真实情境替换这一幕。',x=-900,y=0,scale=1,subtitle='',asset=None,art='<text x="0" y="20" font-size="92" text-anchor="middle" class="blue">为什么？</text><path class="pen accent draw" pathLength="1" d="M-225 65 Q0 100 225 65"/>'),
        dict(id='choice',title='再看一个选择',notes='启动示意：说明如何做出选择，以及反馈是什么。',x=900,y=0,scale=1,subtitle='',asset=None,art='<text x="0" y="20" font-size="80" text-anchor="middle" class="blue">然后，怎么做？</text><text x="0" y="140" font-size="38" text-anchor="middle">用真实经历说明。</text>')]
    (root/'content/scenes.json').write_text(json.dumps(scenes,ensure_ascii=False,indent=2)+'\n')
    (root/'content/script.md').write_text('# 用户原话\n\n尚未输入；启动示意不是用户经历。\n')
    (root/'content/story.md').write_text('# 演示目标\n\n观众、希望发生的改变、核心信息与时长待从自然语言输入中提取。\n')
    (root/'content/evidence.md').write_text('# 事实与来源\n\n未输入正式主张；不得将启动示意作为证据。\n')
    (root/'content/assets.json').write_text('[]\n')
    (root/'.gitignore').write_text('__pycache__/\n.preview-state.json\n.wrangler/\ndist/\n')
    for name in ['build.py','verify.py']:
        subprocess.run([sys.executable,name],cwd=root,check=True,stdout=subprocess.DEVNULL)
    return dict(project=str(root),validated=True,scenes=len(scenes),elapsed_ms=round((time.perf_counter()-start)*1000,2))

if __name__=='__main__':
    ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--project',required=True);args=ap.parse_args()
    try:print(json.dumps(initialize(args.project),ensure_ascii=False))
    except (ValueError,OSError,subprocess.CalledProcessError) as e:raise SystemExit(str(e))
